#!/usr/bin/env node
// Regenerates the metric-matched fallback @font-face rules in src/styles/fonts.css with fontaine.
// The fallbacks are written statically (not via the Vite plugin) so the CSS is deterministic and
// reviewable. Run after replacing any file in public/fonts: `npm run fonts:fallbacks`.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { readMetrics, getMetricsForFamily, generateFontFace } from 'fontaine';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src/styles/fonts.css');
const START = '/* @fallbacks:start (generated by scripts/gen-font-fallbacks.mjs; do not edit by hand) */';
const END = '/* @fallbacks:end */';

const faces = [
  { family: 'Bodoni Moda', file: 'bodoni-moda.woff2', fallbacks: ['Times New Roman'] },
  { family: 'Libre Franklin', file: 'libre-franklin.woff2', fallbacks: ['Arial'] },
  { family: 'Martian Mono', file: 'martian-mono.woff2', fallbacks: ['Courier New'] },
];

const blocks = [];
for (const face of faces) {
  const metrics = await readMetrics(pathToFileURL(join(root, 'public/fonts', face.file)));
  if (!metrics) throw new Error(`could not read metrics for ${face.file}`);
  for (const local of face.fallbacks) {
    const fallbackMetrics = await getMetricsForFamily(local);
    if (!fallbackMetrics) throw new Error(`no capsize metrics for ${local}`);
    blocks.push(
      generateFontFace(metrics, {
        name: `${face.family} fallback`,
        font: local,
        metrics: fallbackMetrics,
      }).trim(),
    );
  }
}

const css = await readFile(target, 'utf8');
const a = css.indexOf(START);
const b = css.indexOf(END);
if (a < 0 || b < 0) throw new Error('fallback markers missing in src/styles/fonts.css');
const next = css.slice(0, a + START.length) + '\n' + blocks.join('\n') + '\n' + css.slice(b);
await writeFile(target, next);
console.log(`wrote ${blocks.length} fallback faces to src/styles/fonts.css`);
